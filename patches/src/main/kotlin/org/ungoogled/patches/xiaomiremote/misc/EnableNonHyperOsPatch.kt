package org.ungoogled.patches.xiaomiremote.misc

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import app.morphe.patcher.patch.resourcePatch
import org.ungoogled.patches.xiaomi.exportDynamicReceivers
import org.ungoogled.patches.xiaomiremote.XiaomiRemoteConstants.COMPATIBILITY_XIAOMI_REMOTE
import org.ungoogled.patches.shared.supportedVersionCheck
import org.w3c.dom.Element

internal const val XIAOMI_REMOTE_EXTENSION = "extensions/xiaomiremote.mpe"

private const val RUNTIME = "Lorg/ungoogled/xiaomiremote/Xiaomi;"

private val log = java.util.logging.Logger.getLogger("XiaomiMiRemote")

/**
 * The app is a data app, installed into /data on a Xiaomi phone; it names a few MIUI-only permissions and asks for a
 * shared user id. An ordinary install is refused those, so they are dropped.
 */
private val manifestPatch = resourcePatch(
    description = "Drops the MIUI-only permissions and shared user id.",
) {
    execute {
        document("AndroidManifest.xml").use { manifest ->
            val root = manifest.documentElement
            root.removeAttribute("android:sharedUserId")

            val usesPermission = manifest.getElementsByTagName("uses-permission")
            val miuiOnly = (0 until usesPermission.length)
                .map { usesPermission.item(it) as Element }
                .filter {
                    val name = it.getAttribute("android:name")
                    name.startsWith("miui.permission.") || name.startsWith("com.xiaomi.permission.") ||
                        name.startsWith("com.miui.permission.")
                }
            for (element in miuiOnly) root.removeChild(element)
        }
    }
}

/**
 * Mi Remote on a phone from another maker.
 *
 * The app reads a few HyperOS classes - miuix's LinearVibrator asks `miui.util.HapticFeedbackUtil`, the system account
 * picker asks `miui.securityspace.CrossUserUtils`, and the bundled Xiaomi account SDK reads device identifiers for its
 * privacy list - and registers broadcast receivers at run time. The extension carries stand-ins for the classes it
 * references (generated by .github/scripts/standins); on a Xiaomi phone the framework's own classes load first, so
 * they never run there.
 *
 * Unlike OnePlus IR Remote, Mi Remote asks Android's own `ConsumerIrManager.hasIrEmitter()` whether the phone can send
 * IR, so no vendor feature has to be faked: a phone with an IR blaster gets the remotes, one without gets the app's
 * "no emitter" screen.
 */
@Suppress("unused")
val enableNonHyperOsPatch = bytecodePatch(
    name = "Enable non-HyperOS ROM support",
    description = "Makes Mi Remote installable and usable on non-Xiaomi ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_XIAOMI_REMOTE)
    dependsOn(supportedVersionCheck(COMPATIBILITY_XIAOMI_REMOTE))
    dependsOn(manifestPatch)
    extendWith(XIAOMI_REMOTE_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through HyperOS: $receivers")
        // Measured against 7.2.5R: 29 calls.
        if (receivers < 20) throw PatchException("only $receivers registerReceiver calls found")

        log.info("HyperOS framework classes answered by the extension")
    }
}
